import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = JSON.parse(fs.readFileSync(path.join(root, 'shared/security-log-catalog.json'), 'utf8'))
const locales = ['zh-Hans', 'en']
for (const [key, entry] of Object.entries(source)) {
  for (const locale of locales) {
    if (typeof entry[locale] !== 'string' || !entry[locale].trim()) throw new Error(`Missing ${locale}: ${key}`)
  }
}
const catalogs = Object.fromEntries(locales.map(locale => [locale,
  Object.fromEntries(Object.entries(source).map(([key, entry]) => [key, entry[locale]])),
]))
const header = '// Generated by scripts/generate-security-log-catalog.mjs. Edit shared/security-log-catalog.json.\n'
const quote = JSON.stringify
const outputs = new Map([
  ['mobile/harmonyos/entry/src/main/ets/generated/GeneratedSecurityLogCatalog.ets', header + 'export const SECURITY_LOG_MESSAGES: Map<string, string> = new Map<string, string>([\n' + Object.entries(catalogs['zh-Hans']).map(([key, value]) => `  [${quote(key)}, ${quote(value)}],`).join('\n') + '\n]);\n'],
  ['web/src/generated/securityLogCatalog.ts', header + 'export const securityLogCatalog: Record<string, Record<string, string>> = ' + JSON.stringify(catalogs, null, 2) + '\n'],
  ['desktop/lib/generated/security_log_catalog.dart', header + 'const Map<String, Map<String, String>> securityLogCatalog = ' + JSON.stringify(catalogs, null, 2) + ';\n'],
  ['mobile/ios/KsuserAuth/Models/GeneratedSecurityLogCatalog.swift', header + 'enum GeneratedSecurityLogCatalog {\n    static let messages: [String: [String: String]] = [\n' + locales.map(locale => `        ${quote(locale)}: [\n` + Object.entries(catalogs[locale]).map(([key, value]) => `            ${quote(key)}: ${quote(value)},`).join('\n') + '\n        ],').join('\n') + '\n    ]\n}\n'],
  ['mobile/android/app/src/main/java/cn/ksuser/auth/core/security/GeneratedSecurityLogCatalog.kt', header + 'package cn.ksuser.auth.core.security\n\nobject GeneratedSecurityLogCatalog {\n    val messages: Map<String, Map<String, String>> = mapOf(\n' + locales.map(locale => `        ${quote(locale)} to mapOf(\n` + Object.entries(catalogs[locale]).map(([key, value]) => `            ${quote(key)} to ${quote(value)},`).join('\n') + '\n        ),').join('\n') + '\n    )\n}\n'],
])
let stale = false
for (const [relative, content] of outputs) {
  const file = path.join(root, relative)
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) {
      console.error(`Stale generated file: ${relative}`)
      stale = true
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(file, content)
  }
}
if (stale) process.exitCode = 1
