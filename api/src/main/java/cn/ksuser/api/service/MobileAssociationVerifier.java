package cn.ksuser.api.service;

import cn.ksuser.api.dto.MobileAppPlatforms;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.DeserializationFeature;
import com.fasterxml.jackson.core.JsonParser;
import org.springframework.stereotype.Component;

import javax.net.ssl.*;
import java.io.*;
import java.net.*;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.util.*;
import java.util.concurrent.*;

/** Fetches association files with a pinned public IP while preserving TLS hostname verification. */
@Component
public class MobileAssociationVerifier {
    private static final int MAX_BODY = 128 * 1024;
    private static final ExecutorService DNS = new ThreadPoolExecutor(2, 2, 0, TimeUnit.SECONDS, new ArrayBlockingQueue<>(16), runnable -> {
        Thread t = new Thread(runnable, "association-dns"); t.setDaemon(true); return t;
    }, new ThreadPoolExecutor.AbortPolicy());
    private static final ScheduledExecutorService DEADLINES = Executors.newSingleThreadScheduledExecutor(runnable -> {
        Thread t = new Thread(runnable, "association-deadlines"); t.setDaemon(true); return t;
    });
    private final ObjectMapper mapper;
    public MobileAssociationVerifier(ObjectMapper mapper) { this.mapper = mapper; }

    public void verifyIos(MobileAppPlatforms.Ios ios) {
        JsonNode root = fetch(URI.create(ios.universalLink()), "/.well-known/apple-app-site-association");
        String app = ios.appIdPrefix() + "." + ios.bundleId();
        URI callback = URI.create(ios.universalLink());
        String path = callback.getPath(), encodedPath = callback.getRawPath();
        boolean link = false;
        for (var detail : root.path("applinks").path("details")) {
            if ((app.equals(detail.path("appID").asText()) || contains(detail.path("appIDs"), app))
                && matchesIosPath(detail, path) && matchesIosPath(detail, encodedPath)) { link = true; break; }
        }
        if (!link) throw failure("AASA 未授权该应用或回调路径");
        if (!contains(root.path("webcredentials").path("apps"), app)) throw failure("AASA 缺少 SDK 网页回退所需的 webcredentials 关联");
    }

    public void verifyAndroid(MobileAppPlatforms.Android android) {
        JsonNode root = fetch(URI.create(android.appLink()), "/.well-known/assetlinks.json");
        if (!root.isArray()) throw failure("assetlinks.json 格式无效");
        Set<String> found = new HashSet<>();
        for (var statement : root) {
            var target = statement.path("target");
            if (contains(statement.path("relation"), "delegate_permission/common.handle_all_urls")
                && "android_app".equals(target.path("namespace").asText()) && android.packageName().equals(target.path("package_name").asText())) {
                if (statement.path("relation_extensions").path("delegate_permission/common.handle_all_urls").has("dynamic_app_link_components")) {
                    throw failure("暂不支持带动态匹配规则的 assetlinks.json，请使用静态关联声明");
                }
                for (var certificate : target.path("sha256_cert_fingerprints")) {
                    if (certificate.isTextual() && certificate.asText().matches("[A-Fa-f0-9]{2}(?::[A-Fa-f0-9]{2}){31}")) found.add(certificate.asText().toUpperCase(Locale.ROOT));
                }
            }
        }
        if (!found.containsAll(android.sha256CertFingerprints())) throw failure("assetlinks.json 包名或证书 SHA-256 指纹不匹配");
    }

    static boolean matchesIosPath(JsonNode detail, String path) {
        if (detail.has("components")) {
            for (var component : detail.path("components")) {
                if (!component.isObject()) return false;
                // Queries are generated by OAuth, and fragments are forbidden. Constrained query/fragment rules
                // cannot establish that all valid code/state callbacks are claimed by the application.
                if (component.has("?") || component.has("#")) return false;
                String rule = component.path("/").asText(null);
                if (rule != null && glob(rule, path)) return !component.path("exclude").asBoolean(false);
            }
            return false;
        }
        for (var node : detail.path("paths")) {
            if (!node.isTextual()) continue;
            String rule = node.asText(); boolean exclude = rule.startsWith("NOT ");
            if (glob(exclude ? rule.substring(4) : rule, path)) return !exclude;
        }
        return false;
    }
    private static boolean glob(String rule, String value) {
        // Association patterns are untrusted. Avoid regex backtracking on repeated wildcard input.
        if (rule.length() > 2048) return false;
        int p = 0, v = 0, star = -1, restart = 0;
        while (v < value.length()) {
            if (p < rule.length() && rule.charAt(p) != '*' && (rule.charAt(p) == '?' || rule.charAt(p) == value.charAt(v))) { p++; v++; }
            else if (p < rule.length() && rule.charAt(p) == '*') { star = p++; restart = v; }
            else if (star >= 0) { p = star + 1; v = ++restart; }
            else return false;
        }
        while (p < rule.length() && rule.charAt(p) == '*') p++;
        return p == rule.length();
    }
    private static boolean contains(JsonNode array, String value) {
        if (!array.isArray()) return false;
        for (var node : array) if (node.isTextual() && value.equals(node.asText())) return true;
        return false;
    }

    JsonNode fetch(URI callback, String path) {
        String host = callback.getHost();
        long deadline = System.nanoTime() + Duration.ofSeconds(8).toNanos();
        try {
            InetAddress[] addresses = resolve(host);
            // A mixed public/private DNS answer is rejected instead of attempting the public subset.
            if (addresses.length == 0 || Arrays.stream(addresses).anyMatch(address -> !isPublic(address))) throw failure("关联域名必须解析为公网地址");
            try (Socket connection = new Socket()) {
                ScheduledFuture<?> closeAtDeadline = DEADLINES.schedule(() -> {
                    try { connection.close(); } catch (IOException ignored) { /* Closing aborts TLS handshakes and slow reads. */ }
                }, Math.max(0, deadline - System.nanoTime()), TimeUnit.NANOSECONDS);
                try {
                    connection.connect(new InetSocketAddress(addresses[0], 443), timeout(deadline));
                    connection.setSoTimeout(timeout(deadline));
                    try (SSLSocket tls = (SSLSocket) ((SSLSocketFactory) SSLSocketFactory.getDefault()).createSocket(connection, host, 443, true)) {
                        SSLParameters parameters = tls.getSSLParameters();
                        parameters.setEndpointIdentificationAlgorithm("HTTPS");
                        parameters.setServerNames(List.of(new SNIHostName(host)));
                        tls.setSSLParameters(parameters);
                        tls.setSoTimeout(timeout(deadline));
                        tls.startHandshake();
                        tls.setSoTimeout(timeout(deadline));
                        OutputStream out = tls.getOutputStream();
                        out.write(("GET " + path + " HTTP/1.1\r\nHost: " + host + "\r\nAccept: application/json\r\nAccept-Encoding: identity\r\nConnection: close\r\nUser-Agent: Ksuser-Association-Verification/1\r\n\r\n").getBytes(StandardCharsets.US_ASCII));
                        out.flush();
                        InputStream in = tls.getInputStream();
                        byte[] body = readResponse(in, tls, deadline);
                        JsonNode result = mapper.reader().with(DeserializationFeature.FAIL_ON_TRAILING_TOKENS).with(JsonParser.Feature.STRICT_DUPLICATE_DETECTION).readTree(body);
                        if (result == null || !result.isContainerNode()) throw failure("关联文件 JSON 格式无效");
                        return result;
                    }
                } finally { closeAtDeadline.cancel(false); }
            }
        } catch (VerificationFailure ex) { throw ex; }
        catch (Exception ex) { throw failure("关联文件获取失败，请检查 HTTPS 证书、网络与 JSON 格式"); }
    }

    static byte[] readResponse(InputStream in, Socket socket, long deadline) throws IOException {
        String status = line(in, socket, deadline, 4096);
        if (!status.matches("HTTP/1\\.[01] 200(?: .*|)")) throw failure("关联文件必须直接返回 HTTP 200，不支持重定向");
        Map<String, String> headers = new HashMap<>(); int headerBytes = status.length();
        while (true) {
            String header = line(in, socket, deadline, 8192); headerBytes += header.length() + 2;
            if (headerBytes > 32768) throw failure("关联文件响应头过大");
            if (header.isEmpty()) break;
            int split = header.indexOf(':'); if (split <= 0) throw failure("关联文件 HTTP 响应无效");
            String name = header.substring(0, split).toLowerCase(Locale.ROOT), value = header.substring(split + 1).trim();
            if (headers.putIfAbsent(name, value) != null && Set.of("content-length", "transfer-encoding", "content-type", "content-encoding").contains(name)) throw failure("关联文件 HTTP 响应无效");
        }
        if (!"application/json".equalsIgnoreCase(headers.getOrDefault("content-type", "").split(";", 2)[0].trim())) throw failure("关联文件 Content-Type 必须为 application/json");
        if (!Set.of("", "identity").contains(headers.getOrDefault("content-encoding", "").toLowerCase(Locale.ROOT))) throw failure("关联文件必须使用未压缩 JSON");
        return body(in, socket, deadline, headers);
    }

    InetAddress[] resolve(String host) throws Exception {
        if (host == null || !host.matches("(?i)[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?") || !host.contains(".") || host.matches("[0-9.]+")) throw failure("关联域名必须使用公网域名");
        Future<InetAddress[]> query = DNS.submit(() -> InetAddress.getAllByName(host));
        try { return query.get(3, TimeUnit.SECONDS); }
        finally { query.cancel(true); }
    }
    static boolean isPublic(InetAddress address) {
        if (address.isAnyLocalAddress() || address.isLoopbackAddress() || address.isLinkLocalAddress() || address.isSiteLocalAddress() || address.isMulticastAddress()) return false;
        byte[] b = address.getAddress(); int a = b[0] & 255, c = b[1] & 255;
        if (b.length == 4) return !(a == 0 || a == 10 || a == 127 || a >= 224 || a == 100 && c >= 64 && c <= 127
            || a == 169 && c == 254 || a == 172 && c >= 16 && c <= 31 || a == 192 && (c == 0 || c == 168 || c == 88 && (b[2] & 255) == 99)
            || a == 198 && (c == 18 || c == 19 || c == 51 && (b[2] & 255) == 100)
            || a == 203 && c == 0 && (b[2] & 255) == 113);
        // Restrict IPv6 to ordinary global unicast, excluding transition/documentation ranges.
        return b.length == 16 && (a & 0xe0) == 0x20 && !(a == 0x20 && c == 0x02)
            && !(a == 0x20 && c == 0x01 && (b[2] & 255) < 2)
            && !(a == 0x20 && c == 0x01 && (b[2] & 255) == 0x0d && (b[3] & 255) == 0xb8)
            && !(a == 0x3f && c == 0xff && (b[2] & 0xf0) == 0);
    }
    private static int timeout(long deadline) {
        long millis = TimeUnit.NANOSECONDS.toMillis(deadline - System.nanoTime());
        if (millis <= 0) throw failure("关联文件验证超时");
        return (int) Math.min(3000, millis);
    }
    private static String line(InputStream in, Socket socket, long deadline, int max) throws IOException {
        ByteArrayOutputStream value = new ByteArrayOutputStream();
        while (value.size() <= max) {
            socket.setSoTimeout(timeout(deadline)); int b = in.read(); if (b < 0) throw new EOFException();
            if (b == '\n') { byte[] bytes = value.toByteArray(); if (bytes.length == 0 || bytes[bytes.length - 1] != '\r') throw new IOException("CRLF required"); return new String(bytes, 0, bytes.length - 1, StandardCharsets.US_ASCII); }
            value.write(b);
        }
        throw failure("关联文件响应头过大");
    }
    private static byte[] body(InputStream in, Socket socket, long deadline, Map<String, String> headers) throws IOException {
        ByteArrayOutputStream value = new ByteArrayOutputStream();
        String transfer = headers.getOrDefault("transfer-encoding", "");
        if (!transfer.isEmpty()) {
            if (!transfer.equalsIgnoreCase("chunked") || headers.containsKey("content-length")) throw new IOException("Invalid transfer encoding");
            while (true) {
                String sizeLine = line(in, socket, deadline, 128); int semicolon = sizeLine.indexOf(';');
                long size = Long.parseLong(semicolon < 0 ? sizeLine : sizeLine.substring(0, semicolon), 16);
                if (size < 0 || size > MAX_BODY - value.size()) throw failure("关联文件超过 128KB");
                if (size == 0) break;
                copy(in, value, socket, deadline, (int) size);
                if (!line(in, socket, deadline, 2).isEmpty()) throw new IOException("Invalid chunk");
            }
        } else if (headers.containsKey("content-length")) {
            long size = Long.parseLong(headers.get("content-length"));
            if (size < 0 || size > MAX_BODY) throw failure("关联文件超过 128KB");
            copy(in, value, socket, deadline, (int) size);
        } else {
            byte[] buffer = new byte[4096]; int count;
            while (true) {
                socket.setSoTimeout(timeout(deadline)); count = in.read(buffer); if (count < 0) break;
                if (count > MAX_BODY - value.size()) throw failure("关联文件超过 128KB"); value.write(buffer, 0, count);
            }
        }
        return value.toByteArray();
    }
    private static void copy(InputStream in, ByteArrayOutputStream out, Socket socket, long deadline, int count) throws IOException {
        byte[] buffer = new byte[4096]; int remaining = count;
        while (remaining > 0) { socket.setSoTimeout(timeout(deadline)); int read = in.read(buffer, 0, Math.min(buffer.length, remaining)); if (read < 0) throw new EOFException(); out.write(buffer, 0, read); remaining -= read; }
    }
    static VerificationFailure failure(String message) { return new VerificationFailure(message); }
    public static class VerificationFailure extends RuntimeException { VerificationFailure(String message) { super(message); } }
}
